"""Sound candidate pruning and component extraction (protocol CANDIDATE).

Input: the candidate G[C(S)] from GraphStore.candidate (block nodes plus their
one-hop neighbours whose sigma code is a query code, induced edges) and the
query graph, both labelled with sigma codes. Output: the targets the solver runs.

  1. Label, degree and neighbour-label filters (LDF and NLF) to a fixpoint.
     A candidate node v survives when some query node u with sigma(u) = sigma(v)
     has deg_Q(u) <= deg(v) and, for every label l, no more l-labelled
     neighbours than v has among the surviving candidate nodes. A pass tests
     every node that lost a neighbour in the previous pass against the nodes
     alive at the start of the pass; passes repeat until nothing is removed or
     the pass cap is reached. Per label only the Pareto-minimal requirement
     vectors are kept, because a node that dominates a larger vector also
     dominates a smaller one.
  2. Connected components of the surviving graph. A connected query maps into a
     single component, so a component is kept only when it has at least as many
     nodes of every label as the query, and at least as many nodes and edges.
  3. Kept components are ordered smallest first (nodes, then edges, then the
     smallest global id). Mode "separate" returns each one as its own target and
     mode "merged" returns their union as one target. Mode "none" (an E9
     ablation) skips step 2 and returns the whole surviving graph.

Soundness: let phi embed Q in G[C(S)]. Before any pass all of phi(V_Q) is alive;
if it is alive at the start of a pass, phi(u) has the distinct alive neighbours
phi(N(u)) with the labels of N(u), so phi(u) meets u's requirement (or a
Pareto-minimal one below it) and survives. By induction no pass removes a node
of phi(V_Q), and phi(V_Q) lies in one kept component. The pass cap only limits
how much is removed. A disconnected query (never generated by queries.py) gets
the merged surviving graph as its single target, which is sound for any query.
"""

from __future__ import annotations

import time
from dataclasses import dataclass, field
from typing import Any

import numpy as np

from . import protocol
from .store import LocalGraph

CHUNK_ENTRIES = 1 << 22  # adjacency entries evaluated per chunk of a pass


# ----------------------------------------------------------------------------
# Query requirements
# ----------------------------------------------------------------------------
@dataclass
class LabelRequirement:
    """Pareto-minimal (degree, neighbour-label count) vectors of the query nodes with one label."""

    degree: np.ndarray  # int64 [r]
    columns: np.ndarray  # int64 [c] label indices with a non-zero count in some vector
    need: np.ndarray  # int64 [r, c]


@dataclass
class QueryRequirements:
    labels: np.ndarray  # int64 [L] sorted distinct query codes
    counts: np.ndarray  # int64 [L] query nodes per label
    per_label: list[LabelRequirement]
    n: int
    m: int
    connected: bool

    def label_index(self, codes: np.ndarray) -> np.ndarray:
        """Index into `labels` of every code, -1 when the code is not a query label."""
        codes = np.asarray(codes, dtype=np.int64)
        pos = np.searchsorted(self.labels, codes)
        inside = pos < self.labels.shape[0]
        pos_c = np.where(inside, pos, 0)
        hit = inside & (self.labels[pos_c] == codes)
        return np.where(hit, pos_c, -1).astype(np.int64)


def pareto_minimal(vectors: np.ndarray) -> np.ndarray:
    """Rows of `vectors` that dominate no other row (componentwise >= and different)."""
    vectors = np.unique(np.asarray(vectors, dtype=np.int64), axis=0)
    keep = np.ones(vectors.shape[0], dtype=bool)
    for i in range(vectors.shape[0]):
        below = (vectors <= vectors[i]).all(axis=1)
        below[i] = False
        if below.any():
            keep[i] = False
    return vectors[keep]


def query_requirements(query: LocalGraph) -> QueryRequirements:
    codes = np.asarray(query.labels, dtype=np.int64)
    labels, inverse, counts = np.unique(codes, return_inverse=True, return_counts=True)
    inverse = inverse.ravel()
    num_labels = labels.shape[0]
    n = query.n
    degree = np.diff(np.asarray(query.indptr, dtype=np.int64))
    rows = np.repeat(np.arange(n, dtype=np.int64), degree)
    nlf = np.bincount(rows * num_labels + inverse[np.asarray(query.indices, dtype=np.int64)],
                      minlength=n * num_labels).reshape(n, num_labels) if n else np.zeros((0, num_labels), np.int64)
    per_label = []
    for i in range(num_labels):
        members = np.flatnonzero(inverse == i)
        minimal = pareto_minimal(np.concatenate([degree[members, None], nlf[members]], axis=1))
        cols = np.flatnonzero(minimal[:, 1:].any(axis=0))
        per_label.append(LabelRequirement(minimal[:, 0].copy(), cols.astype(np.int64), minimal[:, 1:][:, cols].copy()))
    connected = n <= 1 or query.components()[0] == 1
    return QueryRequirements(labels.astype(np.int64), counts.astype(np.int64), per_label, n,
                             query.num_undirected_edges, bool(connected))


# ----------------------------------------------------------------------------
# LDF / NLF fixpoint
# ----------------------------------------------------------------------------
def _segments(indptr: np.ndarray, nodes: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """(lens, flat entry positions) of the CSR rows of `nodes`, in the given node order."""
    starts = indptr[nodes]
    lens = indptr[nodes + 1] - starts
    total = int(lens.sum())
    pos = np.repeat(starts - (np.cumsum(lens) - lens), lens)
    pos += np.arange(total, dtype=np.int64)
    return lens, pos


def _evaluate(graph: LocalGraph, nodes: np.ndarray, lab: np.ndarray, alive: np.ndarray,
              req: QueryRequirements) -> np.ndarray:
    """Survival of `nodes` (sorted by label index) against the alive set."""
    indptr = np.asarray(graph.indptr, dtype=np.int64)
    lens, pos = _segments(indptr, nodes)
    nbrs = np.asarray(graph.indices[pos], dtype=np.int64)
    owner = np.repeat(np.arange(nodes.shape[0], dtype=np.int64), lens)
    live = alive[nbrs]
    degree = np.bincount(owner[live], minlength=nodes.shape[0])
    nbr_lab = lab[nbrs]
    node_lab = lab[nodes]
    survive = np.zeros(nodes.shape[0], dtype=bool)
    group_starts = np.flatnonzero(np.r_[True, node_lab[1:] != node_lab[:-1]])
    group_ends = np.r_[group_starts[1:], nodes.shape[0]]
    entry_offsets = np.r_[0, np.cumsum(lens)]
    for a, b in zip(group_starts.tolist(), group_ends.tolist()):
        rule = req.per_label[int(node_lab[a])]
        d = degree[a:b]
        k = b - a
        if rule.columns.shape[0]:
            col_of = np.full(req.labels.shape[0], -1, dtype=np.int64)
            col_of[rule.columns] = np.arange(rule.columns.shape[0], dtype=np.int64)
            ea, eb = int(entry_offsets[a]), int(entry_offsets[b])
            cols = col_of[np.maximum(nbr_lab[ea:eb], 0)]
            ok = live[ea:eb] & (nbr_lab[ea:eb] >= 0) & (cols >= 0)
            width = rule.columns.shape[0]
            counts = np.bincount((owner[ea:eb][ok] - a) * width + cols[ok], minlength=k * width).reshape(k, width)
        passed = np.zeros(k, dtype=bool)
        for r in range(rule.degree.shape[0]):
            ok_r = d >= rule.degree[r]
            if rule.columns.shape[0]:
                ok_r &= (counts >= rule.need[r]).all(axis=1)
            passed |= ok_r
        survive[a:b] = passed
    return survive


def ldf_nlf_fixpoint(graph: LocalGraph, req: QueryRequirements, *, max_iterations: int | None = None,
                     chunk_entries: int = CHUNK_ENTRIES) -> tuple[np.ndarray, dict[str, Any]]:
    """Alive mask over the candidate's local nodes after the LDF/NLF fixpoint."""
    max_iterations = int(protocol.CANDIDATE["fixpoint_max_iterations"] if max_iterations is None else max_iterations)
    lab = req.label_index(np.asarray(graph.labels, dtype=np.int64))
    alive = lab >= 0
    indptr = np.asarray(graph.indptr, dtype=np.int64)
    degrees = np.diff(indptr)
    # a node with fewer candidate neighbours than the smallest query degree of its label fails every pass
    # that tests it, so it needs no read of its row
    min_degree = np.asarray([int(rule.degree.min()) for rule in req.per_label], dtype=np.int64)
    dirty = alive.copy()
    removed_per_pass: list[int] = []
    passes = 0
    while passes < max_iterations:
        check = np.flatnonzero(dirty & alive)
        if check.shape[0] == 0:
            break
        passes += 1
        dirty[:] = False
        short = degrees[check] < min_degree[lab[check]]
        fail_parts = [check[short]]
        check = check[~short]
        check = check[np.argsort(lab[check], kind="stable")]
        # Chunks hold whole label groups or parts of them; each chunk is evaluated against the same alive set.
        cum = np.cumsum(degrees[check])
        start = 0
        while start < check.shape[0]:
            base = int(cum[start - 1]) if start else 0
            stop = int(np.searchsorted(cum, base + chunk_entries, side="right"))
            stop = min(max(stop, start + 1), check.shape[0])
            part = check[start:stop]
            fail_parts.append(part[~_evaluate(graph, part, lab, alive, req)])
            start = stop
        removed = np.concatenate(fail_parts) if fail_parts else np.zeros(0, dtype=np.int64)
        removed_per_pass.append(int(removed.shape[0]))
        if removed.shape[0] == 0:
            break
        alive[removed] = False
        _, pos = _segments(indptr, np.sort(removed))
        touched = np.asarray(graph.indices[pos], dtype=np.int64)
        dirty[touched] = True
    converged = not (dirty & alive).any() or (removed_per_pass and removed_per_pass[-1] == 0)
    return alive, {
        "label_miss_nodes": int((lab < 0).sum()),
        "passes": passes,
        "removed_per_pass": removed_per_pass,
        "converged": bool(converged),
    }


# ----------------------------------------------------------------------------
# Components
# ----------------------------------------------------------------------------
def split_by_component(graph: LocalGraph, comp: np.ndarray, order: np.ndarray) -> list[LocalGraph]:
    """The induced subgraphs of the listed components, in the given order, in one pass."""
    rank = np.full(int(comp.max(initial=-1)) + 1, -1, dtype=np.int64)
    rank[order] = np.arange(order.shape[0], dtype=np.int64)
    node_rank = rank[comp]
    nodes = np.flatnonzero(node_rank >= 0)
    nodes = nodes[np.argsort(node_rank[nodes], kind="stable")]  # grouped by component, ids ascending within
    sizes = np.bincount(node_rank[nodes], minlength=order.shape[0])
    comp_start = np.r_[0, np.cumsum(sizes)]
    new_local = np.full(graph.n, -1, dtype=np.int64)
    new_local[nodes] = np.arange(nodes.shape[0], dtype=np.int64) - np.repeat(comp_start[:-1], sizes)
    indptr = np.asarray(graph.indptr, dtype=np.int64)
    lens, pos = _segments(indptr, nodes)
    nbrs = new_local[np.asarray(graph.indices[pos], dtype=np.int64)]
    entry_start = np.r_[0, np.cumsum(lens)]
    out = []
    for c in range(order.shape[0]):
        a, b = int(comp_start[c]), int(comp_start[c + 1])
        ea, eb = int(entry_start[a]), int(entry_start[b])
        sub_indptr = np.r_[0, np.cumsum(lens[a:b])].astype(np.int64)
        members = nodes[a:b]
        out.append(LocalGraph(global_ids=np.asarray(graph.global_ids)[members],
                              indptr=sub_indptr, indices=nbrs[ea:eb].astype(np.int32),
                              labels=None if graph.labels is None else np.asarray(graph.labels)[members]))
    return out


@dataclass
class PruneResult:
    targets: list[LocalGraph]
    stats: dict[str, Any] = field(default_factory=dict)
    # For locate(): which candidate nodes survive the filters, the component of every surviving node,
    # the components that pass the component filter (target order) and those the cap keeps.
    alive: np.ndarray | None = field(default=None, repr=False)
    component: np.ndarray | None = field(default=None, repr=False)
    passed: np.ndarray | None = field(default=None, repr=False)
    kept: np.ndarray | None = field(default=None, repr=False)
    mode: str | None = None  # "separate", "merged", "none", or "unpruned" for an unfiltered candidate

    @property
    def empty(self) -> bool:
        return not self.targets


def locate(result: PruneResult, candidate: LocalGraph, nodes: np.ndarray) -> dict[str, Any]:
    """Where a node set (the planted witness, global ids) goes through pruning.

    in_candidate and alive count its nodes in the candidate and after LDF/NLF. component is "kept"
    (target is the index of the target that holds it), "capped" (the component passed the filter and
    the cap dropped it), "filtered" (it failed the size or label test), "split" (its nodes lie in
    several components), "unfiltered" (no component step: mode "none", a disconnected query or an
    unpruned candidate), or None when a node is missing or pruned. A witness inside the candidate is
    never pruned, filtered or split (module docstring), so those outcomes flag a bug.
    """
    nodes = np.asarray(nodes, dtype=np.int64)
    gids = np.asarray(candidate.global_ids, dtype=np.int64)
    pos = np.searchsorted(gids, nodes)  # global_ids are strictly increasing
    inside = pos < gids.shape[0]
    inside[inside] = gids[pos[inside]] == nodes[inside]
    out: dict[str, Any] = {"nodes": int(nodes.shape[0]), "in_candidate": int(inside.sum()), "alive": None,
                           "component": None, "target": None}
    if not inside.all():
        return out
    if result.mode == "unpruned":
        out.update({"alive": int(nodes.shape[0]), "component": "unfiltered", "target": 0 if result.targets else None})
        return out
    if result.alive is None:  # the candidate lacked the query label multiset, so pruning never ran
        return out
    alive = np.asarray(result.alive, dtype=bool)
    out["alive"] = int(alive[pos].sum())
    if out["alive"] < nodes.shape[0]:
        return out
    if result.component is None:
        out.update({"component": "unfiltered", "target": 0 if result.targets else None})
        return out
    rank = np.cumsum(alive)[pos] - 1  # node positions in the pruned graph
    comps = np.unique(np.asarray(result.component)[rank])
    if comps.shape[0] > 1:
        out["component"] = "split"
        return out
    hit = np.flatnonzero(np.asarray(result.kept) == comps[0])
    if hit.shape[0]:
        out.update({"component": "kept", "target": int(hit[0]) if result.mode == "separate" else 0})
    elif (np.asarray(result.passed) == comps[0]).any():
        out["component"] = "capped"
    else:
        out["component"] = "filtered"
    return out


def prune(candidate: LocalGraph, query: LocalGraph, *, mode: str | None = None,
          max_iterations: int | None = None, component_cap: int | None = None,
          requirements: QueryRequirements | None = None) -> PruneResult:
    """Targets for the solver: pruned, component-filtered, smallest first."""
    mode = str(protocol.CANDIDATE["component_mode"] if mode is None else mode)
    if mode not in ("separate", "merged", "none"):
        raise ValueError(f"unknown component mode {mode!r}")
    cap = protocol.CANDIDATE["component_cap"] if component_cap is None else component_cap
    req = requirements or query_requirements(query)
    stats: dict[str, Any] = {"candidate_nodes": candidate.n, "candidate_edges": candidate.num_undirected_edges,
                             "mode": mode, "query_connected": req.connected}
    t0 = time.perf_counter()
    lab_all = req.label_index(np.asarray(candidate.labels, dtype=np.int64))
    have = np.bincount(lab_all[lab_all >= 0], minlength=req.labels.shape[0])
    if (have < req.counts).any() or candidate.n < req.n or candidate.num_undirected_edges < req.m:
        stats.update({"reason_empty": "candidate lacks the query label multiset", "prune_seconds": 0.0,
                      "components_seconds": 0.0, "pruned_nodes": 0, "pruned_edges": 0,
                      "components_total": 0, "components_kept": 0})
        return PruneResult([], stats)
    alive, fix = ldf_nlf_fixpoint(candidate, req, max_iterations=max_iterations)
    pruned = candidate.subgraph(alive)
    t1 = time.perf_counter()
    stats.update(fix)
    stats.update({"prune_seconds": t1 - t0, "pruned_nodes": pruned.n, "pruned_edges": pruned.num_undirected_edges})

    if not req.connected or mode == "none":
        stats.update({"components_seconds": 0.0, "components_total": None, "components_kept": 1 if pruned.n else 0,
                      "note": "no component filter" if req.connected else "disconnected query: merged target"})
        return PruneResult([pruned] if pruned.n else [], stats, alive=alive, mode=mode)

    count, comp = pruned.components()
    sizes = np.bincount(comp, minlength=count) if count else np.zeros(0, dtype=np.int64)
    lens = np.diff(np.asarray(pruned.indptr, dtype=np.int64))
    edges = np.bincount(comp, weights=lens, minlength=count).astype(np.int64) // 2 if count else sizes
    ok = np.flatnonzero((sizes >= req.n) & (edges >= req.m))
    if ok.shape[0]:
        slot = np.full(count, -1, dtype=np.int64)
        slot[ok] = np.arange(ok.shape[0], dtype=np.int64)
        lab = req.label_index(np.asarray(pruned.labels, dtype=np.int64))
        members = slot[comp] >= 0
        per = np.bincount(slot[comp][members] * req.labels.shape[0] + lab[members],
                          minlength=ok.shape[0] * req.labels.shape[0]).reshape(ok.shape[0], req.labels.shape[0])
        ok = ok[(per >= req.counts).all(axis=1)]
    if ok.shape[0]:
        smallest_id = np.full(count, np.iinfo(np.int64).max, dtype=np.int64)
        np.minimum.at(smallest_id, comp, np.asarray(pruned.global_ids, dtype=np.int64))
        ok = ok[np.lexsort((smallest_id[ok], edges[ok], sizes[ok]))]
    passed = ok
    capped = 0
    if cap is not None and ok.shape[0] > int(cap):
        capped = int(ok.shape[0] - int(cap))
        ok = ok[:int(cap)]
    stats.update({"components_total": int(count), "components_kept": int(ok.shape[0]),
                  "components_capped": capped, "kept_sizes": sizes[ok][:20].astype(int).tolist(),
                  "kept_nodes_total": int(sizes[ok].sum())})
    if ok.shape[0] == 0:
        stats["reason_empty"] = "no component covers the query label multiset"
        targets: list[LocalGraph] = []
    elif mode == "separate":
        targets = split_by_component(pruned, comp, ok)
    else:
        keep = np.zeros(count, dtype=bool)
        keep[ok] = True
        targets = [pruned.subgraph(keep[comp])]
    stats["components_seconds"] = time.perf_counter() - t1
    return PruneResult(targets, stats, alive=alive, component=comp, passed=passed, kept=ok, mode=mode)
